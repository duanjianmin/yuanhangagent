WEEKDAYS = "一二三四五六日"


def calendar_text(days: int = 16) -> str:
    """从今天起若干天的“日期 星期”对照表。日期计算交给程序，不交给模型。"""
    today = config.today()
    monday = today - timedelta(days=today.weekday())
    lines = []
    for n in range(days):
        day = today + timedelta(days=n)
        week = (day - monday).days // 7
        label = ("本周", "下周", "下下周")[min(week, 2)] if n else "今天，本周"
        lines.append(f"{day.isoformat()} {label}星期{WEEKDAYS[day.weekday()]}")
    return "\n".join(lines)
